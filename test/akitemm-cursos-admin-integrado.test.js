'use strict';
const {test}=require('node:test');
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const read=file=>fs.readFileSync(path.resolve(__dirname,'..',file),'utf8');
test('Cursos PDF no unico escritorio administrativo, compartilhado entre PC e celular',()=>{
 const html=read('src/candidato/escritorio-admin-candidato-ui.html');
 const js=read('src/candidato/escritorio-admin-candidato-ui.js');
 assert.match(html,/id="tituloProdutosAdmin"/);
 assert.match(html,/id="tituloCursosPdfAdmin"/);
 assert.match(html,/id="listaCursosPdfAdmin"/);
 assert.match(html,/id="resumoCursosPdfAdmin"/);
 assert.match(html,/id="pdfProdutoArquivoAdmin"/);
 assert.match(html,/id="pdfProdutoEnviarAdmin"/);
 assert.match(html,/Gerencie aqui os cursos digitais já cadastrados/);
 assert.match(html,/Cada comprador autorizado poderá baixar uma cópia/);
 assert.equal((html.match(/id="listaCursosPdfAdmin"/g)||[]).length,1);
 assert.match(js,/function renderizarCursosPdfAdmin\(r\)/);
 assert.match(js,/r\.registros\.filter\(item=>item\.produto\.tipo==='PDF'\)/);
 assert.match(js,/Gerenciar curso e PDF/);
 assert.match(js,/renderizarCursosPdfAdmin\(r\)/);
 assert.match(js,/api\(prefixo\+'\/pdf'\)/);
 assert.match(js,/PDF armazenado/);
 assert.match(js,/armazenamento comercial persistente/);
});
test('PDF no servidor comercial permanece privado e versionado',()=>{
 const catalogo=read('src/producao/catalogo-mercadorias-real.js');
 const material=read('src/producao/material-pdf-cursos-real.js');
 const ponte=read('src/producao/ponte-catalogo-real-preview.js');
 const rotas=read('src/candidato/servidor-loja-escritorio-candidato.js');
 assert.match(catalogo,/new MaterialPdfCursosReal/);
 assert.match(catalogo,/PUBLICACAO_EXIGE_PDF/);
 assert.match(catalogo,/x-pdf-versao-esperada/);
 assert.match(material,/akitemm_curso_pdf_versoes_real/);
 assert.match(material,/PDF_HISTORICO_IMUTAVEL/);
 assert.match(ponte,/autorizarOperador,bodyArquivo/);
 assert.match(ponte,/application\/pdf/);
 assert.match(ponte,/checkoutReal:false/);
 assert.match(rotas,/PDF_COMERCIAL_AGUARDANDO_PAGAMENTO_REAL/);
});
