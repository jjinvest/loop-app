'use strict';
const test=require('node:test');
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const src=fs.readFileSync(path.resolve(__dirname,'../src/routes/admin-escritorio-demo.js'),'utf8');
test('Compras individuais do escritorio consultam SQLite sem simular vinculacoes',()=>{
 assert.match(src,/router\.get\('\/escritorio-demo\/clientes\/:id\/compras'/);
 assert.match(src,/FROM admin_ponte_compras_demo/);
 assert.match(src,/WHERE conta_id=\?/);
 assert.match(src,/SELECT COUNT\(\*\) AS n FROM admin_ponte_compras_demo/);
 assert.match(src,/semPagamentosReais:true/);
 assert.match(src,/ciclos:'NAO_CONCILIADOS_NESTA_CONSULTA'/);
 assert.match(src,/FROM admin_ponte_posicoes_adicionais_demo/);
 assert.match(src,/posicoesAdicionais:possuiPosicoesAdicionais\?'CONCILIADAS_SQLITE':'TABELA_AUSENTE'/);
 assert.match(src,/compras:comprasComPosicoes/);
});

test('API SQLite devolve apenas compras do cliente correto e suas posicoes adicionais',async t=>{
 const {once}=require('node:events');
 const os=require('node:os');
 const {RepositorioCatalogoSQLite}=require('../src/domain/repositorio-catalogo-sqlite');
 const {criarAppAdminLaboratorio}=require('../src/laboratorio/servidor-catalogo');
 const dir=fs.mkdtempSync(path.join(os.tmpdir(),'loop-escritorio-relacoes-'));
 t.after(()=>fs.rmSync(dir,{recursive:true,force:true}));
 const repo=new RepositorioCatalogoSQLite({caminho:path.join(dir,'db.sqlite')});
 t.after(()=>repo.fechar());
 const db=repo.banco;
 db.exec(`CREATE TABLE admin_contas_participantes_demo(id TEXT PRIMARY KEY,nome TEXT,indicado_por_id TEXT);
 CREATE TABLE admin_ponte_compras_demo(pedido_id TEXT PRIMARY KEY,conta_id TEXT,produto_id TEXT,valor_centavos INTEGER,confirmado_em TEXT,posicao_id INTEGER);
 CREATE TABLE admin_ponte_posicoes_adicionais_demo(pedido_id TEXT,ordem INTEGER,posicao_id INTEGER);`);
 const a='11111111-1111-1111-1111-111111111111';
 const b='22222222-2222-2222-2222-222222222222';
 db.prepare('INSERT INTO admin_contas_participantes_demo(id,nome) VALUES (?,?)').run(a,'Cliente A');
 db.prepare('INSERT INTO admin_contas_participantes_demo VALUES (?,?)').run(b,'Cliente B');
 const add=db.prepare('INSERT INTO admin_ponte_compras_demo VALUES (?,?,?,?,?,?)');
 add.run('pedido-a',a,'curso',25000,'2026-10-24T10:00:00Z',101);
 add.run('pedido-b',b,'curso',25000,'2026-10-24T11:00:00Z',201);
 db.prepare('INSERT INTO admin_ponte_posicoes_adicionais_demo VALUES (?,?,?)').run('pedido-a',2,102);
 const segredo='token-relacoes-escritorio-teste-123456789012345';
 const app=criarAppAdminLaboratorio({repositorio:repo,segredo});
 const server=app.listen(0,'127.0.0.1');
 await once(server,'listening');
 t.after(()=>new Promise(resolve=>server.close(resolve)));
 const base='http://127.0.0.1:'+server.address().port;
 const uri='/api/admin/escritorio-demo/clientes/'+a+'/compras';
 assert.equal((await fetch(base+uri)).status,401);
 const headers={authorization:'Bearer '+segredo};
 const res=await fetch(base+uri,{headers});
 assert.equal(res.status,200);
 assert.equal(res.headers.get('cache-control'),'no-store');
 const data=await res.json();
 assert.equal(data.totalComprasDocumentadas,1);
 assert.equal(data.compras.length,1);
 assert.equal(data.compras[0].pedidoId,'pedido-a');
 assert.equal(data.compras[0].posicaoId,101);
 assert.deepEqual(data.compras[0].posicoesAdicionais,[{ordem:2,posicaoId:102}]);
 assert.equal(JSON.stringify(data).includes('pedido-b'),false);
 assert.equal(data.semPagamentosReais,true);
 assert.equal((await fetch(base+'/api/admin/escritorio-demo/clientes/'+b+'/compras',{headers})).status,200);
 assert.equal((await fetch(base+'/api/admin/escritorio-demo/clientes/invalido/compras',{headers})).status,400);
 assert.equal((await fetch(base+'/api/admin/escritorio-demo/clientes/33333333-3333-3333-3333-333333333333/compras',{headers})).status,404);
});
